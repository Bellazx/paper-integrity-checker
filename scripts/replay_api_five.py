def save(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix('.tmp')
    temp.write_text(json.dumps(value, ensure_ascii=False, indent=2, default=str))
    temp.replace(path)

def prepare(repo, job):
    job.mkdir(parents=True, exist_ok=False)
    snap = job / 'snapshot'
    snap.mkdir()
    paths = subprocess.check_output(['git', 'ls-files', '-z'], cwd=repo).decode().split('\0')
    # Freeze tracked implementation and assets, excluding all historical datasets.
    allowed = {'api', 'core', 'modules', 'utils', 'review_v3', 'scripts', 'templates', 'assets', 'fonts'}
    selected = set()
    for rel in paths:
        p = Path(rel)
        if rel and (len(p.parts) == 1 or p.parts[0] in allowed):
            if (repo / p).is_file(): selected.add(p)
    # Include new implementation files not committed yet.
    for directory in allowed:
        if (repo / directory).is_dir():
            selected.update(p.relative_to(repo) for p in (repo / directory).rglob('*')
                            if p.is_file() and '__pycache__' not in p.parts and p.suffix != '.pyc')
    hashes = {}
    for rel in sorted(selected):
        dst = snap / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(repo / rel, dst)
        hashes[str(rel)] = hashlib.sha256(dst.read_bytes()).hexdigest()
    (snap / 'venv').symlink_to(repo / 'venv', target_is_directory=True)
    sys.path.insert(0, str(repo))
    from api.services.submission_policy import material_fingerprint
    entries = []
    baseline = repo / 'data/submission_tests/20261106-guest002-75min/project'
    for key, task in BASELINE_TASKS.items():
        old = json.loads((baseline / 'data/tasks' / task / 'status.json').read_text())
        paper = old['papers'][0]
        src = Path(paper['input_dir'])
        dst = snap / 'data/input' / key / src.name
        shutil.copytree(src, dst)
        original_hash = material_fingerprint(str(src))
        copied_hash = material_fingerprint(str(dst))
        if original_hash != copied_hash: raise RuntimeError(f'Input copy mismatch: {key}')
        entries.append({'key': key, 'source_task': task, 'source_input': str(src),
                        'input_dir': str(dst), 'doi': paper['doi'],
                        'submission_no': paper['submission_no'], 'source_language': paper['language'],
                        'language': 'both', 'material_fingerprint': copied_hash,
                        'baseline_seconds': BASELINES[key]})
    save(job / 'manifest.json', {'created_at': datetime.now().isoformat(),
         'commit': subprocess.check_output(['git','rev-parse','HEAD'],cwd=repo,text=True).strip(),
         'code_sha256': hashes, 'papers': entries, 'total_limit_seconds': 4500,
         'report_reserve_seconds': 300, 'database_writes': False,
         'baseline_source': str(baseline),
         'comparison_notes': 'All reports bilingual, matching PDFs actually generated by baseline; baseline en requests also generated Chinese. Current judge rules include separate pre-existing changes.'})
    print(job, flush=True)

async def execute(job):
    snap = job / 'snapshot'
    os.environ.update(PAPER_INTEGRITY_ROOT=str(snap), PAPER_API_DRY_RUN='1',
                      REVIEW_ENGINE='v3', REVIEW_RESUME_RESULTS='0', REVIEW_V3_REGRADE='0',
                      API_PAPER_DEADLINE_SECONDS='4500', API_REPORT_RESERVE_SECONDS='300',
                      OPENBLAS_NUM_THREADS='1', OMP_NUM_THREADS='1', MKL_NUM_THREADS='1',
                      REVIEW_COVERAGE_MEMORY_MB='8192',
                      TMPDIR=str(snap / 'data/runtime_tmp'),
                      PAPER_CHECKER_PYTHON=sys.executable,
                      REVIEW_STATE_DIR=str(snap / 'data/output/review_v2/state'))
    sys.path.insert(0, str(snap))
    from api.models import PaperInfo, TaskConfig, TaskMode, TaskStatus
    from api.services.task_manager import TaskManager
    from api.services import detection_reports_worker as worker
    from review_v3 import config as v3config
    manifest = json.loads((job / 'manifest.json').read_text())
    status = {'pid': os.getpid(), 'started_at': datetime.now().isoformat(), 'state': 'running',
              'papers': {}, 'model': v3config.MODEL, 'judge_model': v3config.JUDGE_MODEL,
              'judge_version': getattr(v3config, 'JUDGE_VERSION', None),
              'session_limit': v3config.MAX_SESSIONS, 'database_writes': False}
    tm = TaskManager()
    task_keys = {}
    def flush(): save(job / 'status.json', status)
    def wrap(name, stage, key_from_args):
        original = getattr(worker, name)
        @functools.wraps(original)
        async def timed(*args, **kwargs):
            key = key_from_args(args, kwargs)
            entry = status['papers'][key]
            start = time.monotonic()
            entry['stage'] = stage
            entry[stage + '_started_at'] = datetime.now().isoformat()
            flush()
            try:
                result = await original(*args, **kwargs)
                if stage == 'review':
                    save(job / key / 'review.json', result)
                    entry['review_result'] = result.get('result')
                    entry['review_metrics'] = result.get('_review_metrics')
                    entry['review_trigger'] = result.get('trigger')
                if stage == 'report':
                    entry['report_metrics'] = args[1].get('_report_metrics')
                    entry['render_errors'] = {k: str(v) for k,v in result.items() if isinstance(v, BaseException)}
                return result
            except BaseException as exc:
                entry[stage + '_error'] = f'{type(exc).__name__}: {exc}'
                raise
            finally:
                entry[stage + '_seconds'] = round(time.monotonic() - start, 3)
                flush()
        setattr(worker, name, timed)
    input_keys = {p['input_dir']: p['key'] for p in manifest['papers']}
    wrap('run_detection_single', 'detection', lambda a,k: input_keys[k['input_dir']])
    wrap('run_review_single', 'review', lambda a,k: input_keys[k['input_dir']])
    wrap('_render_review_pair', 'report', lambda a,k: input_keys[a[0].input_dir])

    async def one(meta):
        key = meta['key']
        config = TaskConfig(submission_no=meta['submission_no'], table_name='detection_reports')
        task_id = tm.create_task(TaskMode.SINGLE, config)
        task_keys[task_id] = key
        paper = PaperInfo(doi_slug=Path(meta['input_dir']).name, doi=meta['doi'],
                         input_dir=meta['input_dir'],
                         output_dir=str(snap / 'data/output/tasks' / task_id / Path(meta['input_dir']).name),
                         submission_no=meta['submission_no'], language=meta['language'],
                         material_fingerprint=meta['material_fingerprint'])
        tm.update_task(task_id, papers=[paper])
        entry = {'task_id':task_id,'state':'running','language':paper.language,
                 'started_at':datetime.now().isoformat(),'baseline_seconds':meta['baseline_seconds']}
        status['papers'][key] = entry
        start = time.monotonic()
        flush()
        try:
            # Watchdog is cleanup-only; never labels an expired run successful.
            await asyncio.wait_for(worker.run_detection_reports_pipeline(task_id, tm, [paper], config.model_dump()), 4515)
            record = tm.get_task(task_id)
            entry.update(state=record.status.value, error=record.error, result=record.result,
                         paper_status=paper.status,paper_error=paper.error)
        except Exception as exc:
            logging.exception('Replay failed: %s', key)
            entry.update(state='failed',error=f'{type(exc).__name__}: {exc}')
            tm.update_task(task_id,status=TaskStatus.FAILED,error=entry['error'])
        finally:
            entry['total_seconds'] = round(time.monotonic()-start,3)
            entry['finished_at'] = datetime.now().isoformat()
            entry['within_75_minutes'] = entry['total_seconds'] <= 4500
            entry['delta_seconds'] = round(entry['total_seconds'] - meta['baseline_seconds'][3],3)
            # Inspect PDFs independently of completion flags.
            import fitz
            pdfs = []
            for root in ('chinese_reports','english_reports','review_v2'):
                folder = snap / 'data/output' / root / 'detection_reports' / task_id
                for path in sorted(folder.glob('*.pdf')):
                    try:
                        with fitz.open(path) as doc:
                            text = '\n'.join(p.get_text() for p in doc)
                            pdfs.append({'path':str(path),'pages':len(doc),'text_chars':len(text),
                                         'images':sum(len(p.get_images()) for p in doc)})
                            out = job / key / (path.stem+'.txt')
                            out.parent.mkdir(parents=True,exist_ok=True)
                            out.write_text(text)
                    except Exception as exc:
                        pdfs.append({'path':str(path),'error':str(exc)})
            entry['pdfs'] = pdfs
            flush()
    async def heartbeat():
        while True:
            status['heartbeat_at'] = datetime.now().isoformat()
            status['load_average'] = os.getloadavg()
            flush()
            await asyncio.sleep(20)
    beat = asyncio.create_task(heartbeat())
    try:
        await asyncio.gather(*(one(p) for p in manifest['papers']))
    finally:
        beat.cancel()
        await asyncio.gather(beat,return_exceptions=True)
        status['finished_at'] = datetime.now().isoformat()
        status['state'] = 'complete' if all(p['state']=='completed' for p in status['papers'].values()) else 'needs_attention'
        flush()

if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prepare',action='store_true')
    parser.add_argument('--job',type=Path,required=True)
    args=parser.parse_args()
    job=args.job.resolve()
    if args.prepare:
        prepare(Path(__file__).resolve().parents[1],job)
    else:
        logging.basicConfig(level=logging.INFO,format='%(asctime)s %(levelname)s %(name)s %(message)s')
        asyncio.run(execute(job))
