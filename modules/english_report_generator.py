def _paper_from_review(review: dict) -> dict:
    report_json = review.get("_report_json")
    if not report_json:
        return {}
    try:
        return (json.loads(Path(report_json).read_text(encoding="utf-8")).get("paper") or {})
    except (OSError, ValueError, TypeError):
        return {}


