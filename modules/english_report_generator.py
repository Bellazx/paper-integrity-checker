_CJK_RE = re.compile(r"[\u3400-\u9fff]")


def _normalize_english_text(value: object) -> str:
    """Translate known internal labels and reject mixed-language report prose."""
    text = str(value or "")
    for chinese, english in _ENGLISH_TERM_REPLACEMENTS:
        text = text.replace(chinese, english)
    return text


def _normalize_english_fields(payload: dict, fields: tuple[str, ...]) -> dict:
    normalized = dict(payload)
    residual = []
    for field in fields:
        value = _normalize_english_text(normalized.get(field, ""))
        normalized[field] = value
        if _CJK_RE.search(value):
            runs = re.findall(r"[\u3400-\u9fff]+", value)
            residual.extend(f"{field}:{run}" for run in runs[:5])
    if residual:
        raise ValueError(
            "English report translation still contains Chinese text: "
            + ", ".join(residual[:10])
        )
    return normalized


def _bind_generated_evidence(text: str, items: list[dict], bind):
    """Assign numbers to renderer-created screenshots before binding them."""
    if not items:
        return bind(text, items)
    from modules.review_report_layout import split_review_issues

    _, issues = split_review_issues(text)
    if not issues:
        return bind(text, items)
    numbered = []
    for item in items:
        if item.get('issue_index') is None:
            position = min(len(numbered), len(issues) - 1)
            item = {**item, 'issue_index': issues[position][0]}
        numbered.append(item)
    return bind(text, numbered)


def _ensure_english_fields(payload: dict, fields: tuple[str, ...]) -> dict:
    """Normalize English fields and run one focused repair for residual CJK."""
    normalized = dict(payload)
    residual_fields = tuple(
        field
        for field in fields
        if _CJK_RE.search(_normalize_english_text(normalized.get(field, "")))
    )
    if not residual_fields:
        return _normalize_english_fields(normalized, fields)

    repair_input = {
        field: _normalize_english_text(normalized.get(field, ""))
        for field in residual_fields
    }
    prompt = """Translate the residual Chinese text in the JSON values into formal English.
Return exactly the same JSON keys. Every value must contain English only, with no Chinese
characters. Preserve filenames, sheet names, panel labels, identifiers, formulas, numbers,
sample sizes, and statistics exactly. Do not summarize, omit, invent, or strengthen evidence.

INPUT:
""" + json.dumps(repair_input, ensure_ascii=False, default=str)
    repaired = _chat_json(prompt, residual_fields, strict_missing=True, temperature=0)
    for field in residual_fields:
        normalized[field] = repaired[field]
    return _normalize_english_fields(normalized, fields)


