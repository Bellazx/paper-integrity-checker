def _evidence_list(findings: dict) -> str:
    sections = (
        ("Image findings", findings.get("image_duplicates", [])),
        ("Image splicing findings", findings.get("image_splicing", [])),
        ("Data findings", findings.get("data_anomalies", [])),
        ("Reference findings", findings.get("reference_issues", [])),
    )
    chunks = []
    for title, items in sections:
        if not items:
            continue
        rows = []
        for index, issue in enumerate(_sample_issues(items, limit=15), 1):
            severity = str(issue.get("severity", "medium")).lower()
            color = "#c00" if severity == "high" else "#b36b00" if severity == "medium" else "#080"
            location = issue.get("location") or issue.get("test") or issue.get("issue_type") or "Screening result"
            description = issue.get("description") or issue.get("details") or "No further description was supplied."
            if isinstance(description, (dict, list)):
                description = json.dumps(description, ensure_ascii=False, default=str)
            rows.append(f'<li style="margin-bottom:4pt;"><span style="color:{color}; font-weight:bold;">{html.escape(severity.upper())}</span> — <b>{html.escape(str(location))}</b>: {html.escape(str(description))}</li>')
        chunks.append(f'<p style="font-size:10pt; font-weight:bold; color:#1a1a1a; margin-top:10pt; margin-bottom:4pt;">{title}</p><ul style="font-size:9.5pt; color:#333; margin:3pt 0 8pt 0;">{"".join(rows)}</ul>')
    return "".join(chunks) or '<p style="font-size:9.5pt; color:#333; margin-bottom:6pt;">No concrete anomaly was retained by the automated screening rules.</p>'


def _clean_issue(issue: dict) -> dict:
    keep = (
        "severity", "test", "issue_type", "location", "description", "details",
        "image_a", "image_b", "page_a", "page_b", "source_a", "source_b",
        "ref_number", "ref_text",
    )
    cleaned = {key: issue.get(key) for key in keep if issue.get(key) not in (None, "", [], {})}
    encoded = json.dumps(cleaned, ensure_ascii=False, default=str)
    if len(encoded) > 3000:
        cleaned["details"] = str(cleaned.get("details", ""))[:1200]
        cleaned["description"] = str(cleaned.get("description", ""))[:1200]
    return cleaned


def _sample_issues(items: list[dict], limit: int = 24) -> list[dict]:
    ordered = sorted(
        (item for item in items if isinstance(item, dict)),
        key=lambda item: {"high": 0, "medium": 1, "low": 2}.get(item.get("severity"), 3),
    )
    return [_clean_issue(item) for item in ordered[:limit]]


def _initial_payload_json(payload: dict) -> str:
    encoded = json.dumps(payload, ensure_ascii=False, default=str)
    if len(encoded) <= 30000:
        return encoded
    compact = dict(payload)
    for key in ("image_findings", "splicing_findings", "data_findings", "reference_findings"):
        compact[key] = compact.get(key, [])[:4]
    return json.dumps(compact, ensure_ascii=False, default=str)


def _chat_json(prompt: str, required: tuple[str, ...], *, strict_missing: bool,
               temperature: float = 0.2, fallback: dict | None = None, attempts: int = 2) -> dict:
    """Ask the report model for a JSON object and parse it, asking once more
    when the reply is not valid JSON.

    One malformed reply (an unescaped quote, a missing comma) used to fail the
    whole API task: on 2026-11-09 a review task failed at this step although the
    same input rendered fine when rerun. The retry quotes the parser error and
    asks for one escaped JSON object; the reply snippet is logged either way so
    the cause is visible in the task error.
    """
    error: Exception | None = None
    for attempt in range(1, attempts + 1):
        response = chat(prompt if attempt == 1 else (
            prompt + "\n\nYour previous reply was not valid JSON (" + str(error) + "). Return exactly one "
            "JSON object and nothing else; escape every double quote, backslash and line break inside "
            "string values."), system=_SYSTEM_PROMPT, temperature=temperature)
        try:
            return _parse_json_response(response, required, strict_missing=strict_missing, fallback=fallback)
        except (json.JSONDecodeError, ValueError) as exc:
            if not isinstance(exc, json.JSONDecodeError) and "did not return JSON" not in str(exc):
                raise  # missing fields etc. are not a formatting problem a retry would fix
            error = exc
            snippet = response.strip().replace("\n", " ")
            log.warning("English report reply %d/%d was not valid JSON (%s); head=%r tail=%r",
                        attempt, attempts, exc, snippet[:200], snippet[-200:])
    raise ValueError(f"English report model returned invalid JSON {attempts} times: {error}")


def _parse_json_response(
    response: str,
    required: tuple[str, ...],
    *,
    strict_missing: bool = False,
    fallback: dict[str, str] | None = None,
) -> dict:
    """Parse a JSON LLM response and validate required string fields.

    ``strict_missing=True`` (default in the *initial* flow) keeps the legacy
    behavior: any blank/missing required key raises so we never silently render
    a half-filled risk overview.

    ``strict_missing=False`` (default in the *review* flow) is the soft path:
    each missing/blank key is filled from ``fallback`` (or the per-key default
    "No material issue was identified in this dimension."). The PDF still
    renders — losing one dimension is preferable to failing the whole report
    when the LLM legitimately has nothing to say about, e.g., methodology.

    JSON parse failures (no object found at all) always raise; we never invent
    structure we can't see.
    """
    response = re.sub(r"^```(?:json)?\s*", "", response.strip(), flags=re.I)
    response = re.sub(r"\s*```$", "", response)
    # Some otherwise valid model responses contain a literal tab/newline inside
    # a quoted prose value.  The JSON standard requires these characters to be
    # escaped, but accepting them here is safe because this parser only consumes
    # the model's local report payload and the resulting value is HTML-escaped
    # before rendering.  Without this tolerant pass one malformed character
    # discarded an otherwise complete English review and marked the API task as
    # failed.
    try:
        parsed = json.loads(response, strict=False)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", response, flags=re.S)
        if not match:
            raise ValueError("English report model did not return JSON")
        parsed = json.loads(match.group(0), strict=False)
    missing = [key for key in required if not str(parsed.get(key, "")).strip()]
    if missing and strict_missing:
        raise ValueError(f"English report response is missing fields: {', '.join(missing)}")
    if missing:
        defaults = {
            "image_review": "No material image-duplication issue was identified.",
            "data_review": "No material data anomaly was identified.",
            "reference_review": "No material reference issue was identified.",
            "methodology_review": "No material methodology or statistical-consistency issue was identified.",
            "verdict": "The review conclusion aligns with the assigned risk level.",
            "reason": "The conclusion follows from the structured review evidence.",
        }
        if fallback:
            defaults.update(fallback)
        log.warning(
            "English report response missing fields %s — filling with defaults (strict_missing=False)",
            ", ".join(missing),
        )
        for key in missing:
            parsed[key] = defaults.get(key, "No material issue was identified in this dimension.")
    return parsed


def _paragraphs(value: object) -> str:
    lines = [line.strip() for line in str(value or "").splitlines() if line.strip()]
    if not lines:
        return "<p>No material issue was identified in this dimension.</p>"
    return "".join(f"<p>{html.escape(line)}</p>" for line in lines)


