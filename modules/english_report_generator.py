def _risk_label(value: str) -> str:
    labels = {
        "高风险": "High Risk",
        "低风险": "Low Risk",
        "建议高风险": "High Risk Recommended",
        "建议低风险": "Low Risk Recommended",
    }
    return labels.get(str(value or "").strip(), str(value or "Unknown"))


def _risk_color(value: str) -> str:
    return "#c00" if "高风险" in str(value or "") or "High Risk" in str(value or "") else "#080"


def _risk_box(label: str, text: str = "") -> str:
    color = _risk_color(label)
    return f'<span style="color:{color}; font-weight:bold;">{html.escape(label)}</span>{html.escape(text)}'


def _dimension_counts(items: list[dict]) -> tuple[int, int, int]:
    return (
        sum(1 for item in items if item.get("severity") == "high"),
        sum(1 for item in items if item.get("severity") == "medium"),
        sum(1 for item in items if item.get("severity") == "low"),
    )


